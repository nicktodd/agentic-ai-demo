#!/usr/bin/env python3
"""
Build triage agent - a small "agentic AI in CI" teaching example.

What it does (one pass, no loop - this is a *single LLM call*, the simplest
tier of agentic design):

  1. Get the Jenkins console log (from a file, or fetched live from Jenkins).
  2. Shrink it to the interesting bits so we send fewer tokens to the model.
  3. Ask Claude to diagnose the failure and write a short markdown report.
  4. Post that report as a comment on the pull request via the GitHub REST API.

Governance notes for learners:
  * The agent ONLY comments. It never pushes code, never re-runs the build,
    never merges. A human reads the comment and decides what to do.
  * Jenkins masks credentials in the console log, and we truncate the log,
    but still treat the log as potentially sensitive - it leaves your network
    when sent to the model API.
  * API keys come from environment variables and are never printed.

Usage examples:
  python3 scripts/triage_agent.py --log-file scripts/sample-failed-build.log \
      --repo example/demo --pr 1 --dry-run
  python3 scripts/triage_agent.py --build-url "$BUILD_URL" \
      --repo my-org/my-repo --pr "$CHANGE_ID"
"""

import argparse
import os
import re
import sys

import requests

# Importing the Anthropic SDK is done lazily inside ask_claude() so the
# "missing API key" check can run (and give a friendly message) even on a
# machine where the SDK is not installed yet.

# Default model: the current Sonnet-class model - fast and cheap enough for a
# CI hook while still strong at reading stack traces. Override with
# ANTHROPIC_MODEL if your organisation standardises on something else.
DEFAULT_MODEL = "claude-sonnet-5-5"

# The system prompt pins the *shape* of the answer so the PR comment is
# consistent build after build. Fixed headings make it skimmable for humans
# and easy to parse later if you want to collect metrics (e.g. how many
# failures were lint vs tests).
SYSTEM_PROMPT = """You are a CI build triage assistant for a Java 21 / Spring Boot 3 / Maven project.
The build runs `mvn -B verify` (unit tests via Surefire, Spotless formatting check, JaCoCo coverage gate).
You will be given a trimmed Jenkins console log. Be concise and factual; do not speculate beyond the log.

Respond in GitHub-flavoured markdown with EXACTLY these sections, in this order:

### 🔍 Build triage
**Failure category:** one of: Compilation, Test failure, Lint/Spotless, Coverage gate, Dependency/Network, Infrastructure/Docker/AWS, Unknown
**Root cause:** 2-3 sentences. Quote the single most important log line in backticks.
**Suggested fix:** bullet points; concrete; name the file, class or test if it is visible in the log.
**Confidence:** High, Medium or Low

End with this exact footer line:
_Generated by the build triage agent — a human still reviews and merges._"""

# Regex of things that usually matter in a failed Maven/Jenkins log.
INTERESTING = re.compile(
    r"ERROR|FAIL|Tests run:|BUILD FAILURE|Exception|Caused by|\[ERROR\]|Rule violated|spotless",
    re.IGNORECASE,
)
ANSI_ESCAPE = re.compile(r"\x1b\[[0-9;]*[A-Za-z]")


# --------------------------------------------------------------------------
# Step 1: obtain the log
# --------------------------------------------------------------------------
def fetch_jenkins_log(build_url: str) -> str:
    """Download `${BUILD_URL}consoleText` (plain text, no HTML) from Jenkins."""
    url = build_url.rstrip("/") + "/consoleText"
    user, token = os.environ.get("JENKINS_USER"), os.environ.get("JENKINS_TOKEN")
    auth = (user, token) if user and token else None  # optional basic auth
    resp = requests.get(url, auth=auth, timeout=60)
    resp.raise_for_status()
    return resp.text


# --------------------------------------------------------------------------
# Step 2: shrink the log
# --------------------------------------------------------------------------
def preprocess_log(raw: str, max_chars: int) -> str:
    """Reduce a noisy console log to what the model actually needs.

    Why bother? Tokens cost money and time, and a 5 MB download log drowns the
    one line that matters. Maven also prints the real failure at the END, so we
    keep the tail, plus any line that looks like an error from anywhere else.
    """
    text = ANSI_ESCAPE.sub("", raw)  # Jenkins/Maven colour codes are noise
    lines = text.splitlines()

    tail = lines[-200:]  # Maven summary + Jenkins "Finished: FAILURE" live here
    tail_set = set(range(max(0, len(lines) - 200), len(lines)))
    # Error-ish lines from the body of the log, with their line number so the
    # model can tell they come from earlier.
    hits = [f"{i + 1}: {line}" for i, line in enumerate(lines)
            if i not in tail_set and INTERESTING.search(line)]

    trimmed = "\n".join(
        ["=== Interesting lines (earlier in the log) ===", *hits[:300],
         "", "=== Last 200 lines ===", *tail]
    )
    # Final safety net: keep the END if it is still too long.
    if len(trimmed) > max_chars:
        trimmed = "[... truncated ...]\n" + trimmed[-max_chars:]
    return trimmed


# --------------------------------------------------------------------------
# Step 3: ask Claude
# --------------------------------------------------------------------------
def ask_claude(log_excerpt: str, model: str) -> str:
    """One Messages API call. Returns the markdown comment body."""
    import anthropic  # imported here so the key check above can run first

    client = anthropic.Anthropic()  # reads ANTHROPIC_API_KEY from the environment
    try:
        response = client.messages.create(
            model=model,
            max_tokens=1024,  # a triage comment is short; cap spend
            system=SYSTEM_PROMPT,
            messages=[{"role": "user", "content":
                       "Diagnose this failed Jenkins build log:\n\n```\n" + log_excerpt + "\n```"}],
        )
    # Most-specific first: tells the learner *which* thing went wrong.
    except anthropic.AuthenticationError:
        fail("Anthropic rejected the API key (401). Check ANTHROPIC_API_KEY.")
    except anthropic.RateLimitError:
        fail("Anthropic rate limit hit (429). Retry later or lower CI concurrency.")
    except anthropic.APIStatusError as e:
        fail(f"Anthropic API error {e.status_code}: {e.message}")
    except anthropic.APIConnectionError as e:
        fail(f"Could not reach the Anthropic API: {e}")

    if response.stop_reason == "refusal":  # safety classifier declined; no text to post
        fail("The model declined to answer (stop_reason=refusal).")
    return "".join(block.text for block in response.content if block.type == "text")


# --------------------------------------------------------------------------
# Step 4: post to GitHub
# --------------------------------------------------------------------------
def post_pr_comment(repo: str, pr: int, body: str, token: str) -> str:
    """PR comments are 'issue comments' in GitHub's API. Returns the comment URL."""
    url = f"https://api.github.com/repos/{repo}/issues/{pr}/comments"
    headers = {
        "Authorization": f"Bearer {token}",
        "Accept": "application/vnd.github+json",
        "X-GitHub-Api-Version": "2022-11-28",
    }
    resp = requests.post(url, headers=headers, json={"body": body}, timeout=30)
    if resp.status_code != 201:
        fail(f"GitHub API returned {resp.status_code}: {resp.text[:300]}")
    return resp.json()["html_url"]


def fail(message: str, code: int = 2) -> None:
    """Print a clear error (never a secret) and exit with a non-zero code."""
    print(f"triage_agent: {message}", file=sys.stderr)
    sys.exit(code)


def main() -> None:
    parser = argparse.ArgumentParser(description="Diagnose a failed Jenkins build with Claude and comment on the PR.")
    source = parser.add_mutually_exclusive_group(required=True)
    source.add_argument("--log-file", help="path to a saved console log")
    source.add_argument("--build-url", help="Jenkins build URL (BUILD_URL); fetches consoleText")
    parser.add_argument("--repo", required=True, help="GitHub repo as owner/name")
    parser.add_argument("--pr", required=True, type=int, help="pull request number")
    parser.add_argument("--dry-run", action="store_true", help="print the comment instead of posting it")
    parser.add_argument("--max-chars", type=int, default=60000, help="max characters of log to send (keeps the end)")
    args = parser.parse_args()

    # Fail fast on configuration problems before spending any tokens.
    if not os.environ.get("ANTHROPIC_API_KEY"):
        fail("ANTHROPIC_API_KEY not set")
    github_token = os.environ.get("GITHUB_TOKEN")
    if not args.dry_run and not github_token:
        fail("GITHUB_TOKEN not set (required unless --dry-run)")
    model = os.environ.get("ANTHROPIC_MODEL", DEFAULT_MODEL)

    if args.log_file:
        with open(args.log_file, encoding="utf-8", errors="replace") as f:
            raw_log = f.read()
    else:
        try:
            raw_log = fetch_jenkins_log(args.build_url)
        except requests.RequestException as e:
            fail(f"Could not fetch Jenkins log: {e}")

    excerpt = preprocess_log(raw_log, args.max_chars)
    print(f"triage_agent: sending {len(excerpt)} chars of log to {model}", file=sys.stderr)
    comment = ask_claude(excerpt, model)

    if args.dry_run:
        print(comment)
        return
    print(f"triage_agent: posted {post_pr_comment(args.repo, args.pr, comment, github_token)}")


if __name__ == "__main__":
    main()
